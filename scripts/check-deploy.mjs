import {readFileSync,existsSync} from 'node:fs';
import {strict as assert} from 'node:assert';
const conf=JSON.parse(readFileSync('vercel.json','utf8'));
assert.equal(conf.services.frontend.root,'frontend');
assert.equal(conf.services.backend.root,'api');
assert.equal(conf.services.frontend.outputDirectory,'dist');
assert.equal(conf.rewrites[0].source,'/api/(.*)');
assert.equal(conf.rewrites[0].destination.service,'backend');
assert.equal(conf.rewrites[1].destination.service,'frontend');
assert(conf.services.frontend.rewrites.some(x=>x.destination==='/index.html'));
assert(existsSync('api/index.js'));
assert(existsSync('api/package.json'));
assert(existsSync('frontend/public/arrita-wordmark.png'));
assert(!existsSync('bun.lock'));
console.log('Services routing configuration checks passed');
